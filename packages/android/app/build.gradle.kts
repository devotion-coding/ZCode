import java.util.Properties

plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.compose)
}

val keystoreProperties = Properties().apply {
    val propertiesFile = rootProject.file("keystore.properties")
    if (propertiesFile.exists()) {
        propertiesFile.inputStream().use { load(it) }
    }
}

fun signingValue(envName: String, propertyName: String): String? =
    System.getenv(envName)?.takeIf { it.isNotBlank() }
        ?: keystoreProperties.getProperty(propertyName)?.takeIf { it.isNotBlank() }

val releaseStoreFilePath = signingValue("ZCODE_ANDROID_KEYSTORE", "storeFile")
val releaseStorePassword = signingValue("ZCODE_ANDROID_KEYSTORE_PASSWORD", "storePassword")
val releaseKeyAlias = signingValue("ZCODE_ANDROID_KEY_ALIAS", "keyAlias")
val releaseKeyPassword = signingValue("ZCODE_ANDROID_KEY_PASSWORD", "keyPassword")
val hasReleaseSigning = !releaseStoreFilePath.isNullOrBlank()

if (hasReleaseSigning && (releaseStorePassword == null || releaseKeyAlias == null || releaseKeyPassword == null)) {
    error(
        "Release signing is partially configured. Set ZCODE_ANDROID_KEYSTORE_PASSWORD, " +
            "ZCODE_ANDROID_KEY_ALIAS and ZCODE_ANDROID_KEY_PASSWORD, or fill keystore.properties.",
    )
}

